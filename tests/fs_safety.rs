//! skillcask never deletes or overwrites data it does not own.
mod common;

use common::*;

const BEGIN: &str = "# >>> skillcask managed block, regenerated by skillcask";
const END: &str = "# <<< skillcask managed block";

fn one(s: &Server) -> Project {
    s.simple("acme/one", "1.0.0", "one");
    let p = Project::new(s);
    p.manifest(s, "\"acme/one\" = \"^1.0\"\n");
    p
}

fn mtime(p: &Project, rel: &str) -> std::time::SystemTime {
    std::fs::metadata(p.path().join(rel)).unwrap().modified().unwrap()
}

#[test]
fn unreadable_gitignore_is_left_byte_identical() {
    let s = Server::start();
    let p = one(&s);
    let gi = b"/vendor\n/caf\xe9\n";
    std::fs::write(p.path().join(".gitignore"), gi).unwrap();
    let o = p.run(&["install"]);
    assert!(!o.status.success(), "{}", String::from_utf8_lossy(&o.stderr));
    assert_eq!(std::fs::read(p.path().join(".gitignore")).unwrap(), gi);

    p.global_manifest(&s, "\"acme/one\" = \"^1.0\"\n");
    let list = p.home().join(".agents/skills/.skillcask-installed");
    std::fs::create_dir_all(list.parent().unwrap()).unwrap();
    std::fs::write(&list, gi).unwrap();
    assert!(!p.run(&["--global", "install"]).status.success());
    assert_eq!(std::fs::read(&list).unwrap(), gi);
}

#[test]
fn crlf_gitignore_keeps_its_line_endings() {
    let s = Server::start();
    let p = one(&s);
    p.write(".gitignore", "/vendor\r\n/secrets.env\r\n");
    p.ok(&["install"]);
    let gi = p.read(".gitignore");
    assert!(gi.starts_with("/vendor\r\n/secrets.env\r\n") && gi.contains("/.agents/skills/one/\r\n"), "{gi:?}");
    assert!(!gi.replace("\r\n", "").contains('\n'), "{gi:?}");
    let before = mtime(&p, ".gitignore");
    std::thread::sleep(std::time::Duration::from_millis(50));
    p.ok(&["install"]);
    assert_eq!(p.read(".gitignore"), gi);
    assert_eq!(mtime(&p, ".gitignore"), before, "the second run rewrote .gitignore");
}

#[test]
fn block_entry_alone_does_not_make_a_store_dir_removable() {
    let s = Server::start();
    let p = Project::new(&s);
    p.manifest(&s, "");
    p.write(".gitignore", &format!("{BEGIN}\n/.agents/skills/mine/\n{END}\n"));
    p.write(".agents/skills/mine/SKILL.md", &skill_md("mine"));
    let out = p.ok(&["install"]);
    assert!(out.contains("warning: kept .agents/skills/mine: modified or not installed by skillcask"), "{out}");
    assert_eq!(p.read(".agents/skills/mine/SKILL.md"), skill_md("mine"));
    assert!(!p.read(".gitignore").contains("mine"), "{}", p.read(".gitignore"));
}

#[test]
fn removing_a_modified_skill_keeps_its_dir() {
    let s = Server::start();
    let p = one(&s);
    p.ok(&["install"]);
    p.write(".agents/skills/one/notes.md", "mine");
    let out = p.ok(&["remove", "acme/one"]);
    assert!(out.contains("warning: kept .agents/skills/one: modified or not installed by skillcask"), "{out}");
    assert_eq!(p.read(".agents/skills/one/notes.md"), "mine");
    assert!(!p.read(".gitignore").contains("/one"));
}

#[test]
fn block_entry_does_not_let_a_new_package_replace_a_hand_written_dir() {
    let s = Server::start();
    s.simple("acme/c", "1.0.0", "mine");
    let p = Project::new(&s);
    p.manifest(&s, "");
    p.write(".gitignore", &format!("{BEGIN}\n/.agents/skills/mine/\n{END}\n"));
    p.write(".agents/skills/mine/SKILL.md", &skill_md("mine"));
    p.write(".agents/skills/mine/notes.md", "keep");
    let out = p.expect(&["add", "acme/c"], 1);
    assert!(out.contains(".agents/skills/mine exists and is not managed by skillcask"), "{out}");
    assert_eq!(p.read(".agents/skills/mine/notes.md"), "keep");
}

#[test]
fn copy_marker_alone_does_not_make_a_stale_project_copy() {
    let s = Server::start();
    let p = Project::new(&s);
    p.manifest(&s, "");
    p.write(".agents/skills/mine/SKILL.md", &skill_md("mine"));
    p.write(".agents/skills/mine/.skillcask-copy", "");
    p.write(".agents/skills/mine/work.md", "keep");
    p.ok(&["install"]);
    assert_eq!(p.read(".agents/skills/mine/work.md"), "keep");
}

#[cfg(unix)]
#[test]
fn dangling_project_link_in_the_store_does_not_break_add() {
    let s = Server::start();
    s.simple("acme/one", "1.0.0", "one");
    let p = Project::new(&s);
    p.manifest(&s, "");
    p.write(".skills/one/SKILL.md", &skill_md("one"));
    p.ok(&["install"]);
    std::fs::remove_dir_all(p.path().join(".skills/one")).unwrap();
    p.ok(&["add", "acme/one"]);
    let meta = std::fs::symlink_metadata(p.path().join(".agents/skills/one")).unwrap();
    assert!(meta.is_dir() && !meta.file_type().is_symlink());
    p.ok(&["status"]);
}

#[test]
fn deleted_hand_written_skill_loses_its_links() {
    let s = Server::start();
    let p = Project::new(&s);
    p.manifest(&s, "");
    p.write(".agents/skills/h/SKILL.md", &skill_md("h"));
    p.ok(&["install"]);
    assert!(p.exists(".claude/skills/h"));
    std::fs::remove_dir_all(p.path().join(".agents/skills/h")).unwrap();
    p.ok(&["install"]);
    assert!(!p.exists(".claude/skills/h") && !p.exists(".junie/skills/h"));
}
